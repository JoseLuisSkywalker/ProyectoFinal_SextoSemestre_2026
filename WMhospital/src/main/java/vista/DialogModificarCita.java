    private void cargarPacientes() {

        PacienteDAO pacienteDAO = new PacienteDAO();

        listaPacientes = pacienteDAO.obtenerTodos();

        jComboBox1.removeAllItems();

        for (Paciente paciente : listaPacientes) {

            jComboBox1.addItem(
                    paciente.getIdPaciente()
                    + " - "
                    + paciente.getNombre()
                    + " "
                    + paciente.getApellido()
            );

        }

        pacienteDAO.cerrarConexion();

    }
    
    private void cargarDatos() {

        for (int i = 0; i < listaPacientes.size(); i++) {

            if (listaPacientes.get(i).getIdPaciente() == cita.getIdPaciente()) {

                jComboBox1.setSelectedIndex(i);

                break;

            }

        }

        jFormattedTextField1.setText(cita.getFechaCita());

        String horaCompleta = cita.getHoraCita();

        String[] partes = horaCompleta.split(" ");

        String horaMinuto = partes[0];

        String ampm = partes[1];

        String[] hm = horaMinuto.split(":");

        jComboBox2.setSelectedItem(hm[0]);

        jComboBox3.setSelectedItem(hm[1]);

        jComboBox4.setSelectedItem(ampm);

        jComboBox5.setSelectedItem(
            String.valueOf(cita.getNumHabitacion())
        );

    }
    
    

