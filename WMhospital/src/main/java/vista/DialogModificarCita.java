    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {

            int indicePaciente = jComboBox1.getSelectedIndex();

            if (indicePaciente < 0) {

                JOptionPane.showMessageDialog(this, "Seleccione un paciente.", "Validación", JOptionPane.WARNING_MESSAGE);
                return;

            }

            Paciente paciente = listaPacientes.get(indicePaciente);
            
            cita.setIdPaciente(
                    paciente.getIdPaciente()
            );

            cita.setIdMedico(
                    paciente.getIdMedico()
            );

            cita.setFechaCita(
                    jFormattedTextField1.getText().trim()
            );

            String horaCita = jComboBox2.getSelectedItem().toString() + ":" + jComboBox3.getSelectedItem().toString()
                    + " " + jComboBox4.getSelectedItem().toString();

            cita.setHoraCita(horaCita);

            cita.setNumHabitacion(Integer.parseInt( jComboBox5.getSelectedItem().toString()));

            CitaDAO citaDAO = new CitaDAO();

            boolean actualizada =

                    citaDAO.actualizar(cita);

            citaDAO.cerrarConexion();

            if (actualizada) {

                JOptionPane.showMessageDialog(

                        this,

                        "Cita modificada correctamente."

                );

                dispose();

            } else {

                JOptionPane.showMessageDialog(

                        this,

                        "No fue posible modificar la cita.",

                        "Error",

                        JOptionPane.ERROR_MESSAGE

                );

            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(

                    this,

                    e.getMessage(),

                    "Error",

                    JOptionPane.ERROR_MESSAGE

            );

        }
       
    }//GEN-LAST:event_jButton1ActionPerformed

